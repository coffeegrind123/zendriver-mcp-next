"""Generate docs/tools.md from the live tool registry.

    python scripts/gen_tool_docs.py          # rewrite docs/tools.md
    python scripts/gen_tool_docs.py --check  # exit 1 if it is out of date (CI)

The reference is generated, never hand-edited, so it cannot drift from the
code: every name, effect, parameter and summary comes from the registered tools.
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
# The reference documents every tool, independent of the caller's environment.
for key in [k for k in os.environ if k.startswith("ZENDRIVER_MCP_")]:
    del os.environ[key]

from zendriver_mcp.registry import SPECS  # noqa: E402
from zendriver_mcp.tools import CATALOG  # noqa: E402
from zendriver_mcp.tools.catalog import CORE, META  # noqa: E402

OUT = ROOT / "docs" / "tools.md"

GROUP_TITLES = {
    "browser": "Browser lifecycle",
    "navigation": "Navigation",
    "tabs": "Tabs",
    "content": "Page content",
    "elements": "Elements",
    "query": "Querying",
    "forms": "Forms and keyboard",
    "humaninput": "Human-like input",
    "utils": "Scripts, screenshots and waits",
    "storage": "Cookies and storage (per page)",
    "cookies": "Cookie jar (whole browser)",
    "logging": "Network and console logs",
    "network": "Network control",
    "interception": "Request interception",
    "proxy": "Proxy",
    "stealth": "Fingerprint and challenges",
    "emulation": "Emulation",
    "permissions": "Permissions",
    "accessibility": "Accessibility",
    "devtools": "Tracing and memory",
    "lighthouse": "Lighthouse",
    "screencast": "Screencast",
}


def _params(schema: dict) -> str:
    props = schema.get("properties") or {}
    required = set(schema.get("required") or [])
    parts = []
    for name in props:
        if name == "tab":
            continue
        parts.append(f"`{name}`" if name in required else f"`{name}?`")
    return ", ".join(parts) or "none"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render() -> str:
    lines = [
        "# Tool reference",
        "",
        "<!-- Generated by scripts/gen_tool_docs.py. Do not edit by hand. -->",
        "",
        f"{len(CATALOG)} tools in {len({s.group for s in SPECS.values()})} groups, plus "
        f"{len(META)} meta-tools ({', '.join(f'`{m}`' for m in META)}).",
        "",
        "**Listed** tools appear in `tools/list` on the default surface; the rest are "
        "reached with `search_tools` and `call_tool` (or listed directly with "
        "`ZENDRIVER_MCP_SURFACE=full`). **Effect** is what the annotations declare: "
        "`read` changes nothing, `write` changes page or browser state, `destructive` "
        "discards state. Tools marked **tab** also take an optional `tab` argument "
        "(`?` marks an optional parameter).",
        "",
    ]
    groups: dict[str, list[str]] = {}
    for name, spec in SPECS.items():
        if name in CATALOG:
            groups.setdefault(spec.group, []).append(name)
    order = [g for g in GROUP_TITLES if g in groups] + sorted(set(groups) - set(GROUP_TITLES))
    for group in order:
        lines += [f"## {GROUP_TITLES.get(group, group)}", ""]
        lines += ["| Tool | Effect | Tab | Listed | Parameters | Summary |"]
        lines += ["|---|---|---|---|---|---|"]
        for name in sorted(groups[group]):
            spec = SPECS[name]
            tool = CATALOG[name]
            lines.append(
                f"| `{name}` | {spec.effect.value} | {'tab' if spec.page_scoped else ''} | "
                f"{'yes' if name in CORE else ''} | {_params(tool.parameters)} | "
                f"{_cell(spec.summary)} |"
            )
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if docs/tools.md is stale")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(
                "docs/tools.md is out of date: run python scripts/gen_tool_docs.py", file=sys.stderr
            )
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
